export const messages: Record<Language, Record<Message, string>> = { es, en, fr, pt }
export const LanguageContext = createContext<{
  language: Language; setLanguage: (language: Language) => void; t: (key: Message) => string
} | null>(null)

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('LanguageProvider is required.')
  return context
}

export function useStableTranslation() {
  const { t } = useLanguage()
  const current = useRef(t)
  useLayoutEffect(() => { current.current = t }, [t])
  // Locale changes must not recreate cleanup callbacks that stop active leases.
  const translate = useCallback((key: Message) => current.current(key), [])
  return { t, translate }
}
