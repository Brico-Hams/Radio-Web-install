param(
    [string]$Source = (Join-Path $PSScriptRoot '..\bricohams-logo.png'),
    [string]$Output = (Join-Path $PSScriptRoot '..\firmware\bricohams\bootlogo.h')
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$image = [System.Drawing.Image]::FromFile((Resolve-Path -LiteralPath $Source))
$bitmap = New-Object System.Drawing.Bitmap 128,48
$graphics = [System.Drawing.Graphics]::FromImage($bitmap)
try {
    $graphics.Clear([System.Drawing.Color]::White)
    $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $height = [single](128 * $image.Height / $image.Width)
    $graphics.DrawImage($image, [single]0, [single]((48 - $height) / 2), [single]128, $height)
    $bytes = for ($page = 0; $page -lt 6; $page++) {
        for ($x = 0; $x -lt 128; $x++) {
            $value = 0
            for ($bit = 0; $bit -lt 8; $bit++) {
                $pixel = $bitmap.GetPixel($x, $page * 8 + $bit)
                $luminance = (299 * $pixel.R + 587 * $pixel.G + 114 * $pixel.B) / 1000
                if ($luminance -lt 190) { $value = $value -bor (1 -shl $bit) }
            }
            '0x{0:X2}' -f $value
        }
    }
    $lines = for ($i = 0; $i -lt $bytes.Count; $i += 16) {
        '    ' + (($bytes[$i..($i + 15)]) -join ', ') + ','
    }
    $hash = (Get-FileHash -LiteralPath $Source -Algorithm SHA256).Hash.ToLowerInvariant()
    $header = @(
        '/* Generated by scripts/generate-bootlogo.ps1 from the Bricohams artwork.'
        " * Source SHA256: $hash"
        ' * 128x48 monochrome adaptation for the radio LCD; original artwork attribution: docs/BRANDING.md.'
        ' */'
        '#ifndef BRICOHAMS_BOOTLOGO_H'
        '#define BRICOHAMS_BOOTLOGO_H'
        '#include <stdint.h>'
        'static const uint8_t BH_BOOTLOGO[768] = {'
        ($lines -join "`n")
        '};'
        '#endif'
        ''
    ) -join "`n"
    [System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($Output), $header, [System.Text.UTF8Encoding]::new($false))
} finally {
    $graphics.Dispose()
    $bitmap.Dispose()
    $image.Dispose()
}
