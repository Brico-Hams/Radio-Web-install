stage_app() {
  local destination=$1 file
  mkdir -p "$destination"
  for file in "${app_files[@]}"; do cp "$root/$file" "$destination/$file"; done
  # Translated help pages (en, de, it, fr) generated by build-help.cjs.
  cp "$root"/ayuda-*.en.html "$root"/ayuda-*.de.html "$root"/ayuda-*.it.html "$root"/ayuda-*.fr.html "$destination/"
  # Vendored Icom custom-firmware patcher (runtime files only), served under the same paths as server.cjs.
  mkdir -p "$destination/third_party/icom-custom-firmware/docs/js" "$destination/third_party/icom-custom-firmware/docs/patches"
  cp "$root/third_party/icom-custom-firmware/LICENSE" "$destination/third_party/icom-custom-firmware/"
  cp "$root"/third_party/icom-custom-firmware/docs/js/{worker,md5,codec,patch}.js "$destination/third_party/icom-custom-firmware/docs/js/"
  cp "$root"/third_party/icom-custom-firmware/docs/patches/*.json "$destination/third_party/icom-custom-firmware/docs/patches/"
  # Diagrams and photos of the UV-K5 V3 atlas, served as docs/atlas/* (same paths as server.cjs).
  mkdir -p "$destination/docs/atlas"
  cp "$root"/docs/atlas/*.jpg "$root"/docs/atlas/*.svg "$destination/docs/atlas/"
  # Printable F4HWN menu manual (PDF), served as docs/manuals/* (same path as server.cjs).
  mkdir -p "$destination/docs/manuals"
  cp "$root"/docs/manuals/*.pdf "$destination/docs/manuals/"
  mkdir -p "$destination/precompiled/apps"
  cp "$root"/precompiled/*.bin "$root"/precompiled/*.json "$root"/precompiled/*.txt "$destination/precompiled/"
  # Signatures travel with the images: the installer refuses unsigned firmware.
  cp "$root"/precompiled/*.sig "$root"/precompiled/SHA256SUMS "$destination/precompiled/"
  cp "$root"/precompiled/apps/*.app "$root"/precompiled/apps/*.json "$destination/precompiled/apps/"
  mkdir -p "$destination/precompiled/chirp"
  cp "$root"/precompiled/chirp/*.py "$root"/precompiled/chirp/*.json "$root"/precompiled/chirp/*.txt "$destination/precompiled/chirp/"
  mkdir -p "$destination/data/channel-templates"
  cp "$root"/data/channel-templates/*.json "$destination/data/channel-templates/"
  if [ -d "$root/templates/repeaters" ]; then
    mkdir -p "$destination/templates"
    cp -R "$root/templates/repeaters" "$destination/templates/repeaters"
  fi
  cp "$root/data/firmware-catalog-fallback.json" "$destination/data/firmware-catalog-fallback.json"
  cp "$root/data/world-land-110m.txt" "$destination/data/world-land-110m.txt"
  cp "$root/data/remote-station-catalog.json" "$destination/data/remote-station-catalog.json"
  cp "$root/data/remote-feature-parity.json" "$destination/data/remote-feature-parity.json"
  cp "$root/data/remote-meter-model.json" "$destination/data/remote-meter-model.json"
  # Windows audio helper spawned by remote-audio.cjs.
  mkdir -p "$destination/scripts"
  cp "$root/scripts/winaudio-out.ps1" "$destination/scripts/winaudio-out.ps1"
  mkdir -p "$destination/node_modules"
  cp -R "$root/node_modules/satellite.js" "$destination/node_modules/satellite.js"
  node - "$destination" <<'NODE'
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const { createHash } = require("node:crypto");
const destination = path.resolve(process.argv[2]);
const { ALLOWED_FILES } = require(path.join(destination, "server.cjs"));
for (const name of ALLOWED_FILES) {
  const file = name === "satellite.min.js" ? "node_modules/satellite.js/dist/satellite.min.js" : name;
  assert(fs.statSync(path.join(destination, file)).isFile(), `Missing installer asset: ${name}`);
}
for (const catalogPath of ["precompiled/catalog.json", "precompiled/apps/catalog.json"]) {
  const catalog = JSON.parse(fs.readFileSync(path.join(destination, catalogPath), "utf8"));
  for (const entry of catalog.entries) {
    const bytes = fs.readFileSync(path.join(destination, entry.path));
    assert.equal(bytes.length, entry.size, `Installer size mismatch: ${entry.path}`);
    assert.equal(createHash("sha256").update(bytes).digest("hex"), entry.sha256,
      `Installer SHA-256 mismatch: ${entry.path}`);
  }
}
NODE
}

download_node() {
  local platform=$1 archive=$2 checksum_file="$work/SHASUMS256.txt" expected actual
  local base="node-v${node_version}-${platform}"
  curl --fail --silent --show-error --location "https://nodejs.org/dist/v${node_version}/${base}.${archive}" -o "$work/${base}.${archive}"
  curl --fail --silent --show-error --location "https://nodejs.org/dist/v${node_version}/SHASUMS256.txt" -o "$checksum_file"
  expected=$(awk -v file="${base}.${archive}" '$2 == file { print $1 }' "$checksum_file")
  if [ -z "$expected" ]; then echo "No hay checksum publicado para ${base}.${archive}" >&2; exit 1; fi
  actual=$(sha256sum "$work/${base}.${archive}" | awk '{print $1}')
  if [ "$actual" != "$expected" ]; then echo "Checksum incorrecto para ${base}.${archive}" >&2; exit 1; fi
}

build_deb() {
  local deb_arch=$1 node_arch=$2
  local package_root="$work/deb-$deb_arch"
  local node_archive="tar.xz"
  download_node "linux-${node_arch}" "$node_archive"
  mkdir -p "$package_root/opt/radicodex/app" "$package_root/opt/radicodex/runtime/node/bin"
  stage_app "$package_root/opt/radicodex/app"
  tar -xJf "$work/node-v${node_version}-linux-${node_arch}.tar.xz" -C "$work"
  install -m 755 "$work/node-v${node_version}-linux-${node_arch}/bin/node" "$package_root/opt/radicodex/runtime/node/bin/node"
  install -m 644 "$work/node-v${node_version}-linux-${node_arch}/LICENSE" "$package_root/opt/radicodex/runtime/node/LICENSE"
  install -D -m 755 "$root/installers/unix/radicodex" "$package_root/usr/bin/radicodex"
  install -D -m 644 "$root/installers/linux/radicodex.desktop" "$package_root/usr/share/applications/radicodex.desktop"
  # Optional headless station: the unit is shipped but never enabled by the package.
  install -D -m 755 "$root/installers/unix/radicodex-station" "$package_root/usr/bin/radicodex-station"
  install -D -m 644 "$root/installers/linux/radicodex-station.service" "$package_root/lib/systemd/system/radicodex-station.service"
  mkdir -p "$package_root/DEBIAN"
  install -m 755 "$root/installers/linux/radicodex-station.postinst" "$package_root/DEBIAN/postinst"
  cat > "$package_root/DEBIAN/control" <<EOF
Package: radicodex
Version: ${version#v}
Section: hamradio
Priority: optional
Architecture: $deb_arch
Depends: libc6 (>= 2.28), libstdc++6, libatomic1
Provides: bricohams-radio-workspace
Replaces: bricohams-radio-workspace
Conflicts: bricohams-radio-workspace
Maintainer: Bricohams
Description: RadiCodex by BricoHams, local radio programming workspace
 RadiCodex by BricoHams local application and Node.js runtime.
EOF
  dpkg-deb --root-owner-group --build "$package_root" "$output/radicodex-${version}-${deb_arch}.deb" >/dev/null
}

