"use strict";
// Regenerates f4hwn-options.js from bricohams-firmware's options/<tag>.json, so the web offers
// exactly the presets and ENABLE_* options that the build workflow accepts.
// Usage: node scripts/f4hwn-options.cjs ../bricohams-firmware/options/v6.3.0.json > f4hwn-options.js
const fs = require("node:fs");

const catalog = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
if (catalog.format !== "bricohams-f4hwn-options" || catalog.version !== 1 || !/^[0-9a-f]{40}$/.test(catalog.upstream?.commit)) {
  throw new Error("Catalogo de opciones F4HWN no reconocido.");
}
process.stdout.write(`// Generated by scripts/f4hwn-options.cjs from bricohams-firmware options/${catalog.upstream.tag}.json. Do not edit.
(function (root) {
  "use strict";
  const R = root.RadioWorkspace = root.RadioWorkspace || {};
  R.F4HWN_OPTIONS = Object.freeze(${JSON.stringify(catalog)});
  if (typeof module !== "undefined") module.exports = R;
})(globalThis);
`);
